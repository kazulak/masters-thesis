# Figure F5: Original P6 Forest Plot (2x2)
# -----------------------------------------------------------------------------
def build_figure_f5() -> None:
    p6_agg_path = REPO_ROOT / 'thesis' / 'synthesis' / 'generated' / 'data' / 'p6_aggregates.csv'
    p6_cell_path = REPO_ROOT / 'thesis' / 'synthesis' / 'generated' / 'data' / 'p6_cells.csv'
    
    with open(p6_agg_path) as f:
        p6_aggs = list(csv.DictReader(f))
    with open(p6_cell_path) as f:
        p6_cells = list(csv.DictReader(f))
        
    contrasts = [
        ('G/F', 'Greedy vs FLOP selection', '(a)'),
        ('F/R', 'FLOP selection vs Reranking', '(b)'),
        ('R/U', 'Reranking vs Guided search', '(c)'),
        ('G/U', 'Greedy vs Guided search', '(d)'),
    ]
    
    fig, axes = plt.subplots(2, 2, figsize=(10.5, 7.2))
    
    for idx, (cnt, desc, letter) in enumerate(contrasts):
        ax = axes[idx // 2, idx % 2]
        
        # Items to display vertically:
        # 1. Overall (all 12 cells)
        # 2. 1 DPU / T8 (6 cells)
        # 3. 4 DPU / T8 (6 cells)
        # 4..9: 6 primary families (1 DPU / T8 and 4 DPU / T8 individual cells)
        rows_to_plot = []
        
        # Aggregates
        for grp, grp_label in [('all', 'Overall (All 12 cells)'),
                               ('1dpu_t8', 'Topology: 1 DPU / T8 (6 cells)'),
                               ('4dpu_t8', 'Topology: 4 DPU / T8 (6 cells)')]:
            match = next((r for r in p6_aggs if r['group'] == grp and r['contrast'] == cnt and r['metric'] == 'session_inclusive_s'), None)
            if match:
                rows_to_plot.append({
                    'label': grp_label,
                    'ratio': float(match['ratio']),
                    'low': float(match['paired_bootstrap_low']),
                    'high': float(match['paired_bootstrap_high']),
                    'is_agg': True,
                    'group': grp,
                })
                
        # Per-cell items
        cells_for_cnt = [r for r in p6_cells if r['contrast'] == cnt and r['metric'] == 'session_inclusive_s']
        # Sort cells deterministically
        cells_for_cnt.sort(key=lambda c: (c['family'], c['topology_id']))
        for c in cells_for_cnt:
            fam_name = c['family']
            topo = c['topology_id'].replace('_', ' ').upper()
            rows_to_plot.append({
                'label': f'{fam_name} ({topo})',
                'ratio': float(c['ratio']),
                'low': float(c['paired_bootstrap_low']),
                'high': float(c['paired_bootstrap_high']),
                'is_agg': False,
                'group': c['topology_id'],
            })
            
        y_pos = list(range(len(rows_to_plot)))
        y_pos.reverse()  # Top to bottom
        
        ax.axvline(1.0, color='#888888', linestyle='--', linewidth=0.9)
        
        for y, r in zip(y_pos, rows_to_plot):
            ratio = r['ratio']
            low = r['low']
            high = r['high']
            
            if r['is_agg']:
                color = '#d62728' if r['group'] == 'all' else ('#1f77b4' if r['group'] == '1dpu_t8' else '#ff7f0e')
                ax.errorbar([ratio], [y], xerr=[[ratio - low], [high - ratio]],
                            fmt='D', markersize=6.5, color=color, capsize=3.5, elinewidth=1.6, zorder=4)
            else:
                color = '#2ca02c' if '1DPU' in r['label'] else '#9467bd'
                ax.errorbar([ratio], [y], xerr=[[max(0, ratio - low)], [max(0, high - ratio)]],
                            fmt='o', markersize=4, color=color, capsize=2, elinewidth=0.8, alpha=0.85, zorder=3)
                
        ax.set_yticks(y_pos)
        ax.set_yticklabels([r['label'] for r in rows_to_plot], fontsize=7.5)
        ax.set_title(f'{letter} Contrast {cnt}: {desc}', fontweight='semibold')
        ax.set_xlabel('Execution time ratio (baseline / alternative)')
        ax.grid(True, axis='x', linestyle='--', alpha=0.5, linewidth=0.5)
        
    save_fig(fig, 'F5_p6_transfer')


