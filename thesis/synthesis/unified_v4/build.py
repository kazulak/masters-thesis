def ablation_labels(manifest: dict) -> dict:
    """Use the frozen arm definitions shared by all primary-family A views."""
    cells = {c['cell_id']: c for c in manifest['calibration_cells']}
    labels = {}
    for stage in ('A0', 'A1', 'A2', 'A3', 'A4'):
        views = [v for v in manifest['calibration_views'] if v['view'] == 'A'
                 and v['point'] == stage and v['cohort'] == 'primary']
        v4_readout.require({v['case_id'] for v in views} == set(CALIBRATION_CASES.values()), 'incomplete A-stage families')
        arms = [cells[v['cell_id']]['arm'] for v in views]
        v4_readout.require(all(a == arms[0] for a in arms), 'inconsistent A-stage arms')
        arm = arms[0]
        schedule = {'serial_nodes_v1': 'serial', 'static_dag_waves_v1': 'static-DAG'}[arm['schedule']]
        fusion = 'fused' if arm['fuse'] else 'unfused'
        topology = f"D{arm['dpus']}/T{arm['tasklets']}"
        description = f'{topology} {schedule} {fusion}'
        if arm['fuse']:
            description += ' (complex launch fusion / four-product fusion)'
        labels[stage] = {'short': f'{stage}\n{topology}\n{schedule}\n{fusion}', 'description': description}
    return labels

def gmean(vals: list[float]) -> float:
    pos = [v for v in vals if v > 0]
    if not pos:
        return 0.0
    return math.exp(sum(math.log(v) for v in pos) / len(pos))

def save_fig(fig: plt.Figure, base_name: str) -> None:
    svg_path = FIG_DIR / f'{base_name}.svg'
    png_path = FIG_DIR / f'{base_name}.png'
    fig.tight_layout(pad=1.2)
    fig.savefig(svg_path, metadata={'Date': None, 'Creator': 'masters-thesis-unified-v4'})
    # Normalize svg lines
    lines = [line.rstrip() for line in svg_path.read_text(encoding='utf-8').splitlines()]
    svg_path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    fig.savefig(png_path, metadata={'Software': 'masters-thesis-unified-v4'})
    plt.close(fig)
    print(f'Saved figure: {base_name}.svg and {base_name}.png')

def make_typst_table(title: str, headers: list[str], rows: list[list[str]], note: str) -> str:
    cols_spec = '(' + ', '.join('1fr' for _ in headers) + ',)'
    lines = [
        '// Generated by thesis/synthesis/unified_v4/build.py; do not edit manually.',
        f'#text(size: 10pt, weight: "bold", {json.dumps(title, ensure_ascii=False)})',
        '#v(4pt)',
        '#{',
        '  set text(size: 8pt)',
        '  table(',
        f'    columns: {cols_spec},',
        '    inset: 4pt,',
        '    stroke: 0.35pt,',
        '    table.header(repeat: true, ' + ', '.join(f'[{h}]' for h in headers) + '),',
    ]
    for row in rows:
        cell_strs = [f'[{c}]' for c in row]
        lines.append('    ' + ', '.join(cell_strs) + ',')
    lines += [
        '  )',
        '}',
        '#v(4pt)',
        f'#text(size: 7.5pt, fill: luma(80), {json.dumps("Note: " + note, ensure_ascii=False)})',
        '',
    ]
    return '\n'.join(lines)


