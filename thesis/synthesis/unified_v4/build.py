def build_checksums() -> None:
    lines = []
    files_to_hash = []
    
    # Figures
    for ext in ['*.svg', '*.png']:
        for p in sorted(FIG_DIR.glob(ext)):
            files_to_hash.append(p)
            
    # Tables
    for p in sorted(TAB_DIR.glob('*.typ')):
        files_to_hash.append(p)
        
    # README
    readme_path = SYNTHESIS_DIR / 'README.md'
    if readme_path.exists():
        files_to_hash.append(readme_path)
        
    for p in files_to_hash:
        rel = p.relative_to(SYNTHESIS_DIR)
        digest = hashlib.sha256(p.read_bytes()).hexdigest()
        lines.append(f'{digest}  {rel}')
        
    checksum_file = SYNTHESIS_DIR / 'SHA256SUMS'
    checksum_file.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'Saved SHA256SUMS with {len(lines)} files')


