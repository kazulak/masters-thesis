# Typst Table T3: Cumulative Ablation
# -----------------------------------------------------------------------------
def build_table_t3(a_rows: list[dict], agg_rows: list[dict]) -> None:
    headers = ['Stage', 'Architecture / Optimization', 'Incremental Ratio', 'Cumulative vs A0', 'Time Reduction', 'GeoMean Speedup']
    
    stage_meta = [
        ('A0', '1 DPU, 1 tasklet, serial, unfused', '1.00×', '1.00×', '0.0%', '1.00×'),
        ('A1', '1 DPU, 24 tasklets, serial, unfused (Tasklet parallelism)', '', '', '', ''),
        ('A2', '4 DPUs, 8 tasklets, serial, unfused (Multi-DPU scaling)', '', '', '', ''),
        ('A3', '4 DPUs, 8 tasklets, serial, fused (Gate fusion)', '', '', '', ''),
        ('A4', '4 DPUs, 8 tasklets, static DAG waves, fused (DAG scheduling)', '', '', '', ''),
    ]
    
    # Calculate geometric means across the 6 primary families
    steps = ['A0', 'A1', 'A2', 'A3', 'A4']
    cum_by_step = {s: [] for s in steps}
    inc_by_step = {'A1': [], 'A2': [], 'A3': [], 'A4': []}
    
    for fam in PRIMARY_FAMILIES:
        cid = CALIBRATION_CASES[fam]
        f_rows = {r['point']: float(r['median_prepared_call_s']) for r in a_rows if r['case_id'] == cid}
        a0 = f_rows['A0']
        for s in steps:
            cum_by_step[s].append(a0 / f_rows[s])
        inc_by_step['A1'].append(f_rows['A0'] / f_rows['A1'])
        inc_by_step['A2'].append(f_rows['A1'] / f_rows['A2'])
        inc_by_step['A3'].append(f_rows['A2'] / f_rows['A3'])
        inc_by_step['A4'].append(f_rows['A3'] / f_rows['A4'])
        
    rows = []
    for idx, s in enumerate(steps):
        name, desc, _, _, _, _ = stage_meta[idx]
        cum_gm = gmean(cum_by_step[s])
        time_red = 100.0 * (1.0 - 1.0 / cum_gm)
        if s == 'A0':
            inc_str = '—'
        else:
            inc_gm = gmean(inc_by_step[s])
            inc_str = f'{inc_gm:.2f}×'
        rows.append([name, desc, inc_str, f'{cum_gm:.2f}×', f'{time_red:.1f}%', f'*{cum_gm:.2f}×*'])
        
    note = (
        'Seven measured blocks. Incremental ratios reflect step-to-step geometric mean speedup across six primary families. '
        'Cumulative ratio is speedup relative to baseline A0. Time reduction is calculated as 100(1 - 1/ratio). '
        'All stages evaluate greedy contraction paths with WRAM panels and packed waves.'
    )
    content = make_typst_table('Cumulative Architectural and Optimization Ablation (A0..A4)', headers, rows, note)
    (TAB_DIR / 'T3_ablation_cumulative.typ').write_text(content, encoding='utf-8')
    print('Saved table: T3_ablation_cumulative.typ')


