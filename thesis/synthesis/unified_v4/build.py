# Figure F1: Tasklet Speedup (2x3)
# -----------------------------------------------------------------------------
def build_figure_f1(t_rows: list[dict]) -> None:
    fig, axes = plt.subplots(2, 3, figsize=(10.5, 6.2), sharex=True, sharey=True)
    letters = ['(a)', '(b)', '(c)', '(d)', '(e)', '(f)']
    
    for idx, fam in enumerate(PRIMARY_FAMILIES):
        ax = axes[idx // 3, idx % 3]
        cid = CALIBRATION_CASES[fam]
        n_q = CALIBRATION_QUBITS[fam]
        fam_title = FAMILY_TITLES[fam]
        letter = letters[idx]
        
        rows = [r for r in t_rows if r['case_id'] == cid]
        data = {}
        for r in rows:
            t = int(r['point'].replace('T', ''))
            med = float(r['median_prepared_call_s'])
            mad = float(r['raw_mad'])
            data[t] = (med, mad)
            
        t1_med, _ = data[1]
        ts = sorted(data.keys())
        speedups = []
        low_err = []
        high_err = []
        for t in ts:
            med, mad = data[t]
            sp = t1_med / med
            sp_low = t1_med / (med + mad) if (med + mad) > 0 else sp
            sp_high = t1_med / (med - mad) if (med - mad) > 0 else sp
            speedups.append(sp)
            low_err.append(max(0.0, sp - sp_low))
            high_err.append(max(0.0, sp_high - sp))
            
        # Plot ideal scaling
        ax.plot([1, 24], [1, 24], color='#888888', linestyle=':', linewidth=1.0, label='Ideal linear ($y=T$)')
        # Plot measured
        ax.errorbar(ts, speedups, yerr=[low_err, high_err], color='#1f77b4', marker='o',
                    markersize=4, linewidth=1.4, capsize=2.5, elinewidth=0.8,
                    label='Measured speedup ($t_{\\mathrm{T1}} / t_{T}$)')
        
        ax.set_title(f'{letter} {fam_title} ($n={n_q}$)', fontweight='semibold')
        ax.set_xticks([1, 4, 8, 12, 16, 20, 24])
        ax.set_xlim(0, 25)
        ax.set_ylim(0.5, 6.0)
        ax.grid(True, linestyle='--', alpha=0.5, linewidth=0.5)
        
        if idx % 3 == 0:
            ax.set_ylabel('Speedup vs T1')
        if idx // 3 == 1:
            ax.set_xlabel('Tasklets $T$ (1 DPU)')
            
    # Add common legend in panel (a)
    axes[0, 0].legend(loc='upper left', framealpha=0.9)
    save_fig(fig, 'F1_tasklet_speedup')


