# Figure F4: Quantization Tradeoff (2x3)
# -----------------------------------------------------------------------------
def build_figure_f4(q_rows: list[dict]) -> None:
    fig, axes = plt.subplots(2, 3, figsize=(10.5, 6.2), sharex=True, sharey=True)
    letters = ['(a)', '(b)', '(c)', '(d)', '(e)', '(f)']
    d_vals = [1, 2, 4, 8, 16, 32, 64]
    
    for idx, fam in enumerate(PRIMARY_FAMILIES):
        ax = axes[idx // 3, idx % 3]
        cid = CALIBRATION_CASES[fam]
        n_q = CALIBRATION_QUBITS[fam]
        fam_title = FAMILY_TITLES[fam]
        letter = letters[idx]
        
        # Cost ratio = f32_time / int8_time (> 1.0 means int8 is faster)
        ratios_t8 = []
        ratios_t24 = []
        for d in d_vals:
            f32_t8 = float(next(r['median_prepared_call_s'] for r in q_rows if r['case_id'] == cid and r['point'] == f'D{d}/T8/split_complex_float32_v1'))
            int8_t8 = float(next(r['median_prepared_call_s'] for r in q_rows if r['case_id'] == cid and r['point'] == f'D{d}/T8/complex_int8_shared_scale_v1'))
            f32_t24 = float(next(r['median_prepared_call_s'] for r in q_rows if r['case_id'] == cid and r['point'] == f'D{d}/T24/split_complex_float32_v1'))
            int8_t24 = float(next(r['median_prepared_call_s'] for r in q_rows if r['case_id'] == cid and r['point'] == f'D{d}/T24/complex_int8_shared_scale_v1'))
            ratios_t8.append(f32_t8 / int8_t8)
            ratios_t24.append(f32_t24 / int8_t24)
            
        ax.axhline(1.0, color='#d62728', linestyle='--', linewidth=0.9, label='Parity ($t_{\\mathrm{f32}} = t_{\\mathrm{int8}}$)')
        ax.plot(d_vals, ratios_t8, color='#2ca02c', marker='^', markersize=5, linewidth=1.4, label='T8 tasklets')
        ax.plot(d_vals, ratios_t24, color='#9467bd', marker='v', markersize=5, linestyle='--', linewidth=1.4, label='T24 tasklets')
        
        ax.set_xscale('log', base=2)
        ax.set_xticks(d_vals)
        ax.set_xticklabels(['1', '2', '4', '8', '16', '32', '64'])
        ax.set_xlim(0.8, 80)
        ax.set_ylim(0.8, 2.30)
        ax.set_title(f'{letter} {fam_title} ($n={n_q}$)', fontweight='semibold')
        ax.grid(True, which='both', linestyle='--', alpha=0.5, linewidth=0.5)
        
