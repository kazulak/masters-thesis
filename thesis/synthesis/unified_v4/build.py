# Typst Table T4: Quantization Error and Cost Tradeoff
# -----------------------------------------------------------------------------
def build_table_t4(q_rows: list[dict], obs_rows: list[dict]) -> None:
    headers = ['Family', 'Qubits ($n$)', 'Matched (D, T)', 'Float32 (s)', 'Int8 (s)', 'Speedup (f32/int8)', 'Max Rel L2 Error', 'Min Fidelity']
    
    # Pick matched D=4, T=24 as representative
    fams = PRIMARY_FAMILIES + ['stress']
    cases = [CALIBRATION_CASES[f] if f in CALIBRATION_CASES else 'stress_n16_l2' for f in fams]
    
    rows = []
    for fam, cid in zip(fams, cases):
        fam_name = FAMILY_TITLES[fam]
        n_val = 16 if 'stress' in fam else CALIBRATION_QUBITS[fam]
        
        # Float32 and Int8 times at D4/T24
        f32_t = float(next(r['median_prepared_call_s'] for r in q_rows if r['case_id'] == cid and r['point'] == 'D4/T24/split_complex_float32_v1'))
        int8_t = float(next(r['median_prepared_call_s'] for r in q_rows if r['case_id'] == cid and r['point'] == 'D4/T24/complex_int8_shared_scale_v1'))
        sp = f32_t / int8_t
        
        # Accuracy metrics from observations
        int8_slots = [r for r in obs_rows if r['case_id'] == cid and 'int8' in r.get('arm', '') and not (r.get('warmup') == 'True' or r.get('warmup') is True)]
        l2_errs = []
        fids = []
        for s in int8_slots:
            val_str = s.get('validation')
            if not val_str or val_str == 'None':
                continue
            try:
                v = json.loads(val_str)
            except Exception:
                try:
                    v = ast.literal_eval(val_str)
                except Exception:
                    continue
            if 'relative_l2' in v:
                l2_errs.append(v['relative_l2'])
            if 'fidelity_normalized' in v:
                fids.append(v['fidelity_normalized'])
                
        max_l2 = f'{max(l2_errs):.2e}' if l2_errs else '—'
        min_fid = f'{min(fids):.6f}' if fids else '—'
        
        rows.append([fam_name, str(n_val), 'D4 / T24', f'{f32_t:.4f}s', f'{int8_t:.4f}s', f'{sp:.2f}×', max_l2, min_fid])
        
    note = (
        'Physical execution on UPMEM hardware at matched topology (4 DPUs, 24 tasklets, static DAG waves). '
        'Speedup > 1.0 indicates int8 runtime advantage. Errors computed against analytic complex128 reference statevectors. '
        'All primary families retain state fidelity > 0.99999.'
    )
    content = make_typst_table('Quantization Trade-Off: Execution Speedup and Numerical Accuracy', headers, rows, note)
    (TAB_DIR / 'T4_quantization_error_cost.typ').write_text(content, encoding='utf-8')
    print('Saved table: T4_quantization_error_cost.typ')


