        letter = letters[idx]
        
        rows = [r for r in w_rows if r['case_id'].startswith(f'{fam}_n')]
        
        # Parse n from case_id
        # Role data: n -> time
        f32_data = {}
        int8_data = {}
        p8_data = {}
        p1_data = {}
        
        for r in rows:
            n = int(r['case_id'].split('_n')[1])
            t = float(r['median_job_to_state_cached_path_s'])
            role = r['role']
            if role == 'upmem_f32':
                f32_data[n] = t
            elif role == 'upmem_int8':
                int8_data[n] = t
            elif role == 'quest32_p8':
                p8_data[n] = t
            elif role == 'quest32_p1':
                p1_data[n] = t
                
        # Sorted x coordinates
        all_ns = sorted(set(list(f32_data.keys()) + list(p8_data.keys())))
        
        # Plot curves
        ns_p8 = sorted(p8_data.keys())
        ax.plot(ns_p8, [p8_data[n] for n in ns_p8], color='#9467bd', marker='D',
                markersize=4, linestyle='-.', linewidth=1.3, label='QuEST CPU (P8, 8 threads)')
        
        ns_p1 = sorted(p1_data.keys())
        ax.plot(ns_p1, [p1_data[n] for n in ns_p1], color='#7f7f7f', marker='^',
                markersize=3.5, linestyle=':', linewidth=1.1, label='QuEST CPU (P1, 1 thread)')
        
        ns_f32 = sorted(f32_data.keys())
        ax.plot(ns_f32, [f32_data[n] for n in ns_f32], color='#1f77b4', marker='o',
                markersize=4.5, linewidth=1.4, label='UPMEM float32 (selected)')
        
        ns_int8 = sorted(int8_data.keys())
        ax.plot(ns_int8, [int8_data[n] for n in ns_int8], color='#2ca02c', marker='s',
                markersize=4.5, linestyle='--', linewidth=1.4, label='UPMEM int8 (selected)')
        
        # Unsupported point at highest n (e.g. n=26 or n=25)
        max_n = max(all_ns)
        if max_n not in f32_data:
            # Mark unsupported boundary explicitly (never zero runtime)
            ax.plot([max_n], [40.0], marker='x', markersize=7, color='#d62728', markeredgewidth=1.8)
            ax.text(max_n, 48.0, 'MRAM\nlimit', color='#d62728', fontsize=6.5, ha='center', va='bottom', fontweight='bold')
            
        ax.set_yscale('log')
        ax.set_xticks(all_ns)
        ax.set_ylim(1e-4, 3e2)
        ax.set_title(f'{letter} {fam_title}', fontweight='semibold')
        ax.grid(True, which='both', linestyle='--', alpha=0.5, linewidth=0.5)
        
